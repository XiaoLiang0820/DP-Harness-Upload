class Translator(QObject):
    """语言管理器：持有当前语言，提供 tr() 翻译，并在切换时通知界面刷新."""

    changed = Signal(str)

    def __init__(self, lang: str = "zh", parent: QObject | None = None) -> None:
        super().__init__(parent)
        self._lang = lang if lang in LANGUAGES else "zh"

    @property
    def lang(self) -> str:
        return self._lang

    def set_lang(self, lang: str) -> None:
        lang = lang if lang in LANGUAGES else "zh"
        if lang != self._lang:
            self._lang = lang
            self.changed.emit(lang)

    def tr(self, key: str, **kwargs) -> str:
        table = _STRINGS.get(key)
        if not table:
            return key
        text = table.get(self._lang) or table.get("zh") or key
        if kwargs:
            try:
                text = text.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                pass
        return text


# 便捷函数：模块级单例（由 MainWindow 创建并全局共享）
_default: Translator | None = None


def get_translator() -> Translator:
    global _default
    if _default is None:
        _default = Translator("zh")
    return _default


def t(key: str, **kwargs) -> str:
    return get_translator().tr(key, **kwargs)
